import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, rmSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root=resolve(import.meta.dirname,'..');
const web=resolve(root,'web');
const output=resolve(web,'.deploy');
execFileSync('npm',['run','build'],{cwd:web,stdio:'inherit'});
rmSync(output,{recursive:true,force:true});
mkdirSync(output,{recursive:true});
cpSync(resolve(web,'.next/standalone'),output,{recursive:true,verbatimSymlinks:true});
rmSync(resolve(output,'data'),{recursive:true,force:true});
cpSync(resolve(web,'.next/static'),resolve(output,'.next/static'),{recursive:true});
cpSync(resolve(web,'public'),resolve(output,'public'),{recursive:true});
for(const name of ['scrape','backup','notify','setup-push'])execFileSync(resolve(web,'node_modules/.bin/esbuild'),[resolve(web,`scripts/${name}.ts`),'--bundle','--platform=node','--format=cjs','--target=node24','--external:better-sqlite3','--external:playwright-core',`--outfile=${resolve(output,name+'.cjs')}`],{stdio:'inherit'});
mkdirSync(resolve(output,'scripts'),{recursive:true});
cpSync(resolve(web,'scripts/fetch-browser.py'),resolve(output,'scripts/fetch-browser.py'));
cpSync(resolve(web,'node_modules/playwright-core'),resolve(output,'node_modules/playwright-core'),{recursive:true,verbatimSymlinks:true});
const version=JSON.parse(readFileSync(resolve(web,'node_modules/better-sqlite3/package.json'),'utf8')).version;
writeFileSync(resolve(output,'sqlite-version'),version+'\n');
execFileSync('tar',['-czf',resolve(web,'lacultureta-release.tgz'),'-C',output,'.'],{stdio:'inherit'});
console.log(resolve(web,'lacultureta-release.tgz'));
